export const PRESETS: InkPreset[] = STYLES.map((style) => ({
  ...style,
  ink: { ...NO_INK_EFFECTS, ...style.ink },
  paper: { ...NO_PAPER_EFFECTS, ...style.paper },
}));

export function createDefaultDoc(format: FormatId = '4:3'): InkDoc {
  const preset = PRESETS[0];
  return {
    source: 'text',
    format,
    seed: 42,
    logoScale: 60,
    typography: preset.typography,
    ink: preset.ink,
    paper: preset.paper,
    motion: { mode: 'bleed-in', duration: 3.5, speed: 1 },
    presetId: preset.id,
    basePresetId: preset.id,
    brandLocked: false,
  };
}

